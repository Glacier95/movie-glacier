import { electronExecutable } from './electron-path.mjs';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { _electron as electron } from 'playwright-core';
import { Store } from '../dist-electron/electron/store.js';
import { backgroundBlurDefault, appearanceDefaults, appearanceControls } from '../dist-electron/src/shared.js';

fs.mkdirSync('.cache', { recursive: true });
const data = fs.mkdtempSync(path.resolve('.cache/appearance-'));
const media = path.join(data, 'media'); fs.mkdirSync(media); fs.mkdirSync(path.join(data, 'images'));
const poster = `${'c'.repeat(40)}.png`;
fs.copyFileSync('build/icon.png', path.join(data, 'images', poster));
const store = await Store.open(path.join(data, 'library.sqlite'), path.resolve('dist-electron/sql-wasm.wasm'), { isEncryptionAvailable: () => false, encryptString: () => Buffer.alloc(0), decryptString: () => '' });
const id = store.createWork('movie', 'Appearance preview', 2020);
store.setWorkFields(id, { poster, titleEn: 'Appearance preview', matchState: 'matched' });
const file = path.join(media, 'fixture.mkv'); fs.writeFileSync(file, 'fixture');
store.putAsset({ workId: id, root: media, path: file, kind: 'file', season: null, episode: null, size: 1, mtimeMs: 1 }, Date.now());
store.setRoots([media]); store.setSetting('backgroundBlur', '17'); store.close();
const packaged = process.env.FILM_LIBRARY_PACKAGED === '1';
const launch = () => electron.launch({ executablePath: electronExecutable(packaged), args: packaged ? ['--no-sandbox', '--disable-gpu'] : ['--no-sandbox', '--disable-gpu', '.'], env: { ...process.env, FILM_LIBRARY_DATA_DIR: data, FILM_LIBRARY_SMOKE: '1' } });
const subset = settings => Object.fromEntries(appearanceControls.map(({ key }) => [key, settings[key]]));
let app;
try {
  app = await launch(); let page = await app.firstWindow(); page.setDefaultTimeout(15_000);
  await page.locator('.poster-card').waitFor();
  assert.deepEqual(subset(await page.evaluate(() => window.library.getSettings())), appearanceDefaults);
  assert.equal((await page.evaluate(() => window.library.getSettings())).backgroundBlur, 17, 'existing background preference is preserved');
  for (const { key, min, max } of appearanceControls) for (const value of [min - 1, max + 1, 1.5, null]) await assert.rejects(page.evaluate(patch => window.library.setSettings(patch), { [key]: value }));
  const openSettings = () => page.getByRole('banner').getByRole('button', { name: '设置', exact: true }).click();
  const slider = name => page.getByRole('slider', { name, exact: true });
  const css = selector => page.locator(selector).first().evaluate(el => ({ filter: getComputedStyle(el).filter, backdrop: getComputedStyle(el).backdropFilter, opacity: getComputedStyle(el).opacity, background: getComputedStyle(el).backgroundImage }));
  await openSettings();
  await slider('背景模糊程度').press('Home');
  await slider('悬停背景不透明度').press('End'); await slider('悬停背景亮度').press('End'); await slider('悬停背景色彩饱和度').press('Home');
  await page.waitForTimeout(550);
  assert.equal((await css('.ambient-image')).filter, 'blur(0px) saturate(0) brightness(1)');
  assert.equal((await css('.ambient-image')).opacity, '1', 'settings preview supplies a poster without hover');
  await slider('面板毛玻璃模糊程度').press('Home'); await slider('面板背景不透明度').press('End');
  assert.match((await css('.settings-modal')).backdrop, /blur\(0px\)/);
  assert.doesNotMatch((await css('.settings-modal')).background, /rgba/);
  assert.deepEqual(subset(await page.evaluate(() => window.library.getSettings())), appearanceDefaults);
  await page.getByRole('button', { name: '取消', exact: true }).click();
  assert.match((await css('.topbar')).backdrop, /blur\(16px\)/);
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await page.locator('.overview-panel').first().waitFor();
  await openSettings(); await slider('面板毛玻璃模糊程度').press('Home'); await slider('面板背景不透明度').press('Home');
  assert.match((await css('.overview-panel')).backdrop, /blur\(0px\)/);
  assert.match((await css('.overview-panel')).background, /rgba\([^)]*, 0\)/);
  await slider('悬停背景不透明度').press('End'); await slider('悬停背景亮度').press('End'); await slider('悬停背景色彩饱和度').press('Home'); await slider('背景模糊程度').press('Home');
  await page.getByRole('button', { name: '保存设置', exact: true }).click();
  const expected = { panelBlur: 0, panelOpacity: 0, backgroundOpacity: 100, backgroundSaturation: 0, backgroundBrightness: 100 };
  assert.deepEqual(subset(await page.evaluate(() => window.library.getSettings())), expected);
  await app.close(); app = await launch(); page = await app.firstWindow(); page.setDefaultTimeout(15_000);
  await page.locator('.poster-card').waitFor();
  assert.deepEqual(subset(await page.evaluate(() => window.library.getSettings())), expected);
  await page.locator('.poster-open').hover(); await page.waitForTimeout(550);
  assert.equal((await css('.ambient-image')).filter, 'blur(0px) saturate(0) brightness(1)');
  assert.equal((await css('.ambient-image')).opacity, '1');
  await openSettings();
  await page.locator('.panel-settings').getByRole('button', { name: '恢复默认效果', exact: true }).click();
  await page.locator('.ambient-settings').getByRole('button', { name: '恢复默认效果', exact: true }).click();
  await page.locator('.panel-settings').scrollIntoViewIfNeeded(); await page.screenshot({ path: path.resolve('.cache/appearance-controls.png') });
  await page.getByRole('button', { name: '保存设置', exact: true }).click();
  assert.deepEqual(subset(await page.evaluate(() => window.library.getSettings())), appearanceDefaults);
  assert.equal((await page.evaluate(() => window.library.getSettings())).backgroundBlur, backgroundBlurDefault);
  await page.evaluate(() => window.library.setSettings({ language: 'en' }));
  await page.getByRole('banner').getByRole('button', { name: 'Settings', exact: true }).click();
  assert.doesNotMatch(await page.getByRole('dialog').innerText(), /[\u3400-\u9fff]/);
  console.log('Appearance settings passed: preview, cancel, validation, preserved old values, restart, hover rendering, reset and English.');
} finally { await app?.close(); }

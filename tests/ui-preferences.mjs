import { electronExecutable } from './electron-path.mjs';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { _electron as electron } from 'playwright-core';
import { Store } from '../dist-electron/electron/store.js';

const data = fs.mkdtempSync(path.resolve('.cache/preferences-'));
const media = path.join(data, 'media');
fs.mkdirSync(media);
const file = path.join(media, 'Ex.Machina.2014.mkv');
fs.writeFileSync(file, 'fixture');
const store = await Store.open(path.join(data, 'library.sqlite'), path.resolve('dist-electron/sql-wasm.wasm'), {
  isEncryptionAvailable: () => false, encryptString: () => Buffer.alloc(0), decryptString: () => ''
});
const id = store.createWork('movie', 'Ex Machina', 2014);
store.setWorkFields(id, { titleEn: 'Ex Machina', titleZh: '机械姬', doubanTitleZh: '机械姬', overview: 'A programmer meets an artificial intelligence.', doubanOverviewZh: '程序员与人工智能的故事。', genres: ['Science Fiction', 'Drama'], doubanTags: ['科幻', '剧情'], directors: [{ id: '1', name: '亚历克斯·加兰', originalName: 'Alex Garland' }], matchState: 'matched' });
store.putAsset({ workId: id, root: media, path: file, kind: 'file', season: null, episode: null, size: 100, mtimeMs: 1 }, Date.now());
store.setRoots([media]);
store.close();
const launch = () => electron.launch({ executablePath: electronExecutable(false), args: ['--no-sandbox', '--disable-gpu', '.'], env: { ...process.env, FILM_LIBRARY_DATA_DIR: data, FILM_LIBRARY_SMOKE: '1' } });
let app;
try {
  app = await launch();
  let page = await app.firstWindow();
  await page.locator('.poster-card').waitFor();
  assert.match(await page.locator('.poster-subtitle').innerText(), /机械姬/);
  await page.getByRole('button', { name: '筛选', exact: true }).click();
  const chip = page.locator('.scroll-chips .chip').first();
  await chip.hover();
  await page.waitForTimeout(350);
  const bounds = await chip.boundingBox(), scroll = await page.locator('.scroll-chips').boundingBox();
  assert.ok(bounds.y >= scroll.y, 'hovered director chip stays inside its scroll clip');
  assert.ok(bounds.y + bounds.height <= scroll.y + scroll.height);
  const glass = await page.locator('.filter-panel').evaluate(el => ({ filter: getComputedStyle(el).backdropFilter, color: getComputedStyle(el).backgroundColor }));
  assert.match(glass.filter, /blur/);
  assert.equal(glass.color, 'rgba(0, 0, 0, 0)');
  await page.screenshot({ path: path.resolve('.cache/preferences-chinese.png') });
  await page.getByRole('banner').getByRole('button', { name: '设置', exact: true }).click();
  await page.getByRole('button', { name: 'English', exact: true }).click();
  await page.getByRole('button', { name: '保存设置', exact: true }).click();
  await page.getByRole('banner').getByRole('button', { name: 'Settings', exact: true }).waitFor();
  assert.doesNotMatch(await page.locator('body').innerText(), /[\u3400-\u9fff]/);
  await page.getByRole('button', { name: /Sort: Recently added/ }).click();
  assert.match(await page.getByRole('listbox').innerText(), /Douban rating/);
  await page.keyboard.press('Escape');
  await page.locator('.poster-open').click();
  assert.doesNotMatch(await page.locator('.detail-view').innerText(), /[\u3400-\u9fff]/);
  await page.screenshot({ path: path.resolve('.cache/preferences-english-detail.png') });
  await page.getByRole('button', { name: 'Edit details', exact: true }).click();
  assert.equal(await page.getByText('Chinese title', { exact: true }).count(), 0);
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('banner').getByRole('button', { name: 'Settings', exact: true }).click();
  assert.doesNotMatch(await page.getByRole('dialog').innerText(), /[\u3400-\u9fff]/);
  await page.getByRole('button', { name: 'Test connection and credentials', exact: true }).click();
  await page.getByText('TMDB read access token is missing', { exact: true }).waitFor();
  assert.doesNotMatch(await page.getByRole('dialog').innerText(), /[\u3400-\u9fff]/);
  await page.screenshot({ path: path.resolve('.cache/preferences-english-settings.png') });
  assert.equal((await page.evaluate(() => window.library.getSettings())).language, 'en');
  const paths = await app.evaluate(({ app }) => [app.getPath('userData'), app.getPath('sessionData')]);
  assert.deepEqual(paths, [data, data]);
  await app.close(); app = await launch(); page = await app.firstWindow();
  await page.getByRole('banner').getByRole('button', { name: 'Settings', exact: true }).waitFor();
  assert.equal(await page.locator('.poster-subtitle').innerText(), '2014');
  await page.getByRole('banner').getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Chinese', exact: true }).click();
  await page.getByRole('button', { name: 'Save settings', exact: true }).click();
  await page.getByRole('banner').getByRole('button', { name: '设置', exact: true }).waitFor();
  assert.match(await page.locator('.poster-subtitle').innerText(), /机械姬/);
  console.log('Language persistence, Chinese preservation, glass surfaces, director clipping and storage paths passed.');
} finally { await app?.close(); }
